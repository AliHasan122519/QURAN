def years(head):
    m = re.match(r'\(\s*(\d+)\s*-\s*(نحو )?(\d+)\s*ه\s*=\s*(\d+)\s*-\s*(نحو )?(\d+)\s*م\s*\)', head)
    if not m: raise SystemExit('date line: ' + head)
    b, nd, d, bm, nm, dm = m.groups()
    birth = f'{int(b)} هـ ({int(bm)} م)' if int(b) else ''
    death = f'{nd or ""}{int(d)} هـ ({nm or ""}{int(dm)} م)'
    return birth, death
