def grab(text, a, b=None, incl=True):
    """the piece of `text` that starts where `a` matches and ends where `b` matches (word for word)"""
    m = re.search(a, text)
    if not m: raise SystemExit('not found: ' + a)
    s = text[m.start():] if b else m.group(0)
    if b:
        e = re.search(b, s)
        if not e: raise SystemExit('end not found: ' + b)
        s = s[:e.end() if incl else e.start()]
    return re.sub(r'\s+([.،؛:؟])', r'\1', re.sub(r'\s+', ' ', s)).strip(' ؛،')
def within(text, context, value):
    """a word or two of a sentence that is in the dictionary (the sentence itself is checked to be there)"""
    c = re.sub(r'\s+', ' ', context)
    if c not in re.sub(r'\s+', ' ', text) or value not in c: raise SystemExit('not found: ' + context)
    return value
def after(text, a, b=None):
    """what follows the label that `a` matches (the label itself is not part of the value)"""
    m = re.search(a, text)
    if not m: raise SystemExit('not found: ' + a)
    return grab(text[m.end():], r'\S', b)
